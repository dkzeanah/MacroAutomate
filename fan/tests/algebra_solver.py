"""Exact algebra verifier. JSON only; model expressions never enter eval/parse_expr.

The AHK app invokes this fixed helper, not code generated by the model.
Supports real finite solutions of algebraic equations/systems in up to 3 variables.
"""
import ast
import json
import re
import sys
import sympy as sp


def normalize(text):
    # Algebra notation only; this never evaluates or enables arbitrary names.
    text = text.replace("−", "-").replace("×", "*").replace("÷", "/")
    text = text.replace("²", "^2").replace("³", "^3").replace("^", "**")
    text = re.sub(r"(?<=[0-9)])\s*(?=[xyz(])", "*", text)
    text = re.sub(r"(?<=[xyz])\s*(?=\()", "*", text)
    text = re.sub(r"(?<=[xyz])\s+(?=[xyz])", "*", text)
    text = re.sub(r"\b[xyz]{2,3}\b", lambda m: "*".join(m.group()), text)
    return text.strip()


class Algebra:
    def __init__(self, names, rational_powers=False):
        self.rational_powers = rational_powers
        if not isinstance(names, list) or not 1 <= len(names) <= 3:
            raise ValueError("Specify 1..3 variables")
        if len(set(names)) != len(names) or any(n not in ("x", "y", "z") for n in names):
            raise ValueError("Only unique x, y, z variables are supported")
        self.symbols = {n: sp.Symbol(n, real=True) for n in names}
        self.denominators = []
        self.radicals = []

    def parse(self, text):
        if not isinstance(text, str) or len(text) > 400:
            raise ValueError("Expression must be a string of at most 400 characters")
        text = normalize(text)
        tree = ast.parse(text, mode="eval")
        if sum(1 for _ in ast.walk(tree)) > 160:
            raise ValueError("Expression too complex")

        def visit(node, depth=0):
            if depth > 24:
                raise ValueError("Expression nesting limit")
            if isinstance(node, ast.Constant) and type(node.value) in (int, float):
                segment = ast.get_source_segment(text, node)
                if len(segment) > 25 or abs(node.value) > 10**12:
                    raise ValueError("Number out of bounds")
                return sp.Rational(segment)
            if isinstance(node, ast.Name) and node.id in self.symbols:
                return self.symbols[node.id]
            if isinstance(node, ast.UnaryOp) and isinstance(node.op, (ast.UAdd, ast.USub)):
                value = visit(node.operand, depth+1)
                return -value if isinstance(node.op, ast.USub) else value
            if isinstance(node, ast.BinOp):
                a, b = visit(node.left, depth+1), visit(node.right, depth+1)
                if isinstance(node.op, ast.Add): return a+b
                if isinstance(node.op, ast.Sub): return a-b
                if isinstance(node.op, ast.Mult): return a*b
                if isinstance(node.op, ast.Div):
                    if b == 0: raise ValueError("Division by zero")
                    self.denominators.append(b)
                    return a/b
                if isinstance(node.op, ast.Pow):
                    if self.rational_powers and b.is_Rational and not b.is_Integer:
                        if abs(b.p) > 8 or b.q > 12:
                            raise ValueError("Rational exponent out of bounds")
                        if a.is_negative is True and b.q % 2:
                            return sp.real_root(a, b.q) ** b.p
                        return a ** b
                    if not b.is_Integer or abs(b) > 8:
                        raise ValueError("Only integer powers -8..8 are supported; use sqrt for roots")
                    if b < 0: self.denominators.append(a)
                    return a**b
            if (isinstance(node, ast.Call) and isinstance(node.func, ast.Name)
                    and node.func.id == "sqrt" and len(node.args) == 1 and not node.keywords):
                value = visit(node.args[0], depth+1)
                self.radicals.append(value)
                return sp.sqrt(value)
            raise ValueError("Unsupported expression syntax; use explicit multiplication and sqrt")
        return visit(tree.body)


def simplify_expression(document):
    algebra = Algebra(["x"], rational_powers=True)
    expression = document.get("expression")
    value = sp.simplify(algebra.parse(expression))
    if value.free_symbols:
        raise ValueError("A numeric expression is required")
    if value.has(sp.zoo, sp.oo, -sp.oo, sp.nan):
        raise ValueError("Expression is undefined")
    not_real = value.is_real is False
    if value.is_real is None:
        raise ValueError("The real domain could not be verified")
    return {"ok": True, "library": "SymPy " + sp.__version__, "expression": expression,
            "value": "" if not_real else sp.sstr(value), "not_real": not_real,
            "domain": "real", "error": ""}


def solve(document):
    if document.get("mode") == "simplify":
        return simplify_expression(document)
    algebra = Algebra(document.get("variables"))
    equations = document.get("equations")
    if not isinstance(equations, list) or not 1 <= len(equations) <= 3:
        raise ValueError("Specify 1..3 equations")
    expressions = []
    for equation in equations:
        if not isinstance(equation, str) or equation.count("=") != 1:
            raise ValueError("Each equation must contain exactly one equals sign")
        left, right = equation.split("=")
        expressions.append(algebra.parse(left) - algebra.parse(right))
    symbols = list(algebra.symbols.values())
    if len(symbols) == 1 and len(expressions) == 1:
        roots = sp.solveset(expressions[0], symbols[0], domain=sp.S.Reals)
        if not isinstance(roots, sp.FiniteSet):
            raise ValueError("Solution is infinite or unresolved; manual review required")
        candidates = [{symbols[0]: root} for root in sorted(roots, key=sp.default_sort_key)]
    else:
        candidates = sp.solve(expressions, symbols, dict=True, check=True)
    if len(candidates) > 16:
        raise ValueError("More than 16 solutions; review required")
    verified = []
    checks = []
    for candidate in candidates:
        if set(candidate) != set(symbols) or any(v.free_symbols or v.is_real is not True for v in candidate.values()):
            raise ValueError("Parametric/non-real solution requires review")
        residuals = [sp.simplify(e.subs(candidate)) for e in expressions]
        denominators = [sp.simplify(d.subs(candidate)) for d in algebra.denominators]
        radicals = [sp.simplify(r.subs(candidate)) for r in algebra.radicals]
        valid = (all(r == 0 for r in residuals) and all(d.is_zero is False for d in denominators)
                 and all(r.is_nonnegative is True for r in radicals))
        checks.append({"candidate": {str(k): sp.sstr(v) for k, v in candidate.items()},
                       "residuals": [sp.sstr(r) for r in residuals],
                       "denominators": [sp.sstr(d) for d in denominators], "valid": valid})
        if valid: verified.append({str(k): sp.sstr(candidate[k]) for k in symbols})
    if not verified:
        raise ValueError("No verified finite real solution; review required")
    proposed = document.get("proposed_solutions", [])
    matched = False
    if proposed:
        normalized = []
        for solution in proposed:
            if not isinstance(solution, dict) or set(solution) != set(algebra.symbols):
                raise ValueError("Malformed proposed solution")
            normalized.append({k: sp.sstr(sp.simplify(algebra.parse(str(v)))) for k, v in solution.items()})
        canonical = lambda items: sorted(json.dumps(item, sort_keys=True) for item in items)
        matched = canonical(normalized) == canonical(verified)
    return {"ok": True, "library": "SymPy " + sp.__version__, "equations": equations,
            "normalized_equations": [normalize(e) for e in equations],
            "variables": list(algebra.symbols), "solutions": verified, "checks": checks,
            "proposed_matched": matched, "domain": "real", "error": ""}


if __name__ == "__main__":
    try:
        if len(sys.argv) != 3:
            raise ValueError("Expected fixed JSON input/output file paths")
        with open(sys.argv[1], encoding="utf-8-sig") as source:
            request = json.load(source)
        result = solve(request)
    except Exception as exc:
        result = {"ok": False, "error": str(exc)}
    with open(sys.argv[2], "w", encoding="utf-8") as target:
        json.dump(result, target, ensure_ascii=False)
